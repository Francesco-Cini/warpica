import numpy as np

def take_finite_difference_2(A, k_1, k_2, delta, phi_phi_flag):
        
    s = A.shape
    B = np.zeros(s)     

    if s[k_1] >= 5 and s[k_2] >= 5:
        if k_1 == k_2:
            match k_1:
                case 1:
                    B[2:-2, :, :, :] = (-(A[4:, :, :, :]-A[:-4, :, :, :]) + 16 * (A[3:-1, :, :, :] - A[1:-3, :, :, :]) - 30 * A[2:-2, :, :, :]) / (12 * (delta[k_1] ** 2))
                    B[0, :, :, :] = B[2, :, :, :]
                    B[1, :, :, :] = B[2, :, :, :]
                    B[-2, :, :, :] = B[-3, :, :, :]
                    B[-1, :, :, :] = B[-3, :, :, :]
                case 2:
                    B[:, 2:-2, :, :] = (-(A[:, 4:, :, :]-A[:, :-4, :, :]) + 16 * (A[:, 3:-1, :, :] - A[:, 1:-3, :, :]) - 30 * A[:, 2:-2, :, :]) / (12 * (delta[k_1] ** 2))
                    B[:, 0, :, :] = B[:, 2, :, :]
                    B[:, 1, :, :] = B[:, 2, :, :]
                    B[:, -2, :, :] = B[:, -3, :, :]
                    B[:, -1, :, :] = B[:, -3, :, :]
                case 3:
                    B[:, :, 2:-2, :] = (-(A[:, :, 4:, :]-A[:, :, :-4, :]) + 16 * (A[:, :, 3:-1, :] - A[:, :, 1:-3, :]) - 30 * A[:, :, 2:-2, :]) / (12 * (delta[k_1] ** 2))
                    if phi_phi_flag:
                        B[:, :, 0, :] = -2
                        B[:, :, 1, :] = -2
                        B[:, :, -2, :] = 2 
                        B[:, :, -1, :] = 2 
                    else:
                        B[:, :, -2, :] = B[:, :, -3, :]
                        B[:, :, -1, :] = B[:, :, -3, :]
                        B[:, :, 0, :] = B[:, :, 2, :]
                        B[:, :, 1, :] = B[:, :, 2, :]
                case 4:
                    B[:, :, :, 2:-2] = (-(A[:, :, :, 4:]-A[:, :, :, :-4]) + 16 * (A[:, :, :, 3:-1] - A[:, :, :, 1:-3]) - 30 * A[:, :, :, 2:-2]) / (12 * (delta[k_1] ** 2))
                    B[:, :, :, 0] = B[:, :, :, 2]
                    B[:, :, :, 1] = B[:, :, :, 2]
                    B[:, :, :, -2] = B[:, :, :, -3]
                    B[:, :, :, -1] = B[:, :, :, -3]
        else:
            k_L = np.max(np.array([k_1, k_2]))
            k_S = np.min(np.array([k_1, k_2]))

            x2 = slice(4, s[k_S - 1])
            x1 = slice(3, s[k_S - 1] - 1)
            x0 = slice(2, s[k_S - 1] - 2)
            x_n1 = slice(1, s[k_S - 1] - 3)
            x_n2 = slice(0, s[k_S - 1] - 4)

            y2 = slice(4, s[k_L - 1])
            y1 = slice(3, s[k_L - 1] - 1)
            y0 = slice(2, s[k_L - 1] - 2)
            y_n1 = slice(1, s[k_L - 1] - 3)
            y_n2 = slice(0, s[k_L - 1] - 4)

            match k_S:
                case 1:
                    match k_L:
                        case 2:
                            B[x0, y0, :, :] = (
                                1 / (12**2 * delta[k_L - 1] * delta[k_S - 1])
                            ) * (
                                -(
                                    -(A[x2, y2, :, :] - A[x_n2, y2, :, :])
                                    + 8 * (A[x1, y2, :, :] - A[x_n1, y2, :, :])
                                )
                                + (
                                    -(A[x2, y_n2, :, :] - A[x_n2, y_n2, :, :])
                                    + 8 * (A[x1, y_n2, :, :] - A[x_n1, y_n2, :, :])
                                )
                                + 8 * (
                                    -(A[x2, y1, :, :] - A[x_n2, y1, :, :])
                                    + 8 * (A[x1, y1, :, :] - A[x_n1, y1, :, :])
                                )
                                - 8 * (
                                    -(A[x2, y_n1, :, :] - A[x_n2, y_n1, :, :])
                                    + 8 * (A[x1, y_n1, :, :] - A[x_n1, y_n1, :, :])
                                )
                            )

                        case 3:
                            B[x0, :, y0, :] = (
                                1 / (12**2 * delta[k_L - 1] * delta[k_S - 1])
                            ) * (
                                -(
                                    -(A[x2, :, y2, :] - A[x_n2, :, y2, :])
                                    + 8 * (A[x1, :, y2, :] - A[x_n1, :, y2, :])
                                )
                                + (
                                    -(A[x2, :, y_n2, :] - A[x_n2, :, y_n2, :])
                                    + 8 * (A[x1, :, y_n2, :] - A[x_n1, :, y_n2, :])
                                )
                                + 8 * (
                                    -(A[x2, :, y1, :] - A[x_n2, :, y1, :])
                                    + 8 * (A[x1, :, y1, :] - A[x_n1, :, y1, :])
                                )
                                - 8 * (
                                    -(A[x2, :, y_n1, :] - A[x_n2, :, y_n1, :])
                                    + 8 * (A[x1, :, y_n1, :] - A[x_n1, :, y_n1, :])
                                )
                            )

                        case 4:
                            B[x0, :, :, y0] = (
                                1 / (12**2 * delta[k_L - 1] * delta[k_S - 1])
                            ) * (
                                -(
                                    -(A[x2, :, :, y2] - A[x_n2, :, :, y2])
                                    + 8 * (A[x1, :, :, y2] - A[x_n1, :, :, y2])
                                )
                                + (
                                    -(A[x2, :, :, y_n2] - A[x_n2, :, :, y_n2])
                                    + 8 * (A[x1, :, :, y_n2] - A[x_n1, :, :, y_n2])
                                )
                                + 8 * (
                                    -(A[x2, :, :, y1] - A[x_n2, :, :, y1])
                                    + 8 * (A[x1, :, :, y1] - A[x_n1, :, :, y1])
                                )
                                - 8 * (
                                    -(A[x2, :, :, y_n1] - A[x_n2, :, :, y_n1])
                                    + 8 * (A[x1, :, :, y_n1] - A[x_n1, :, :, y_n1])
                                )
                            )

                case 2:
                    match k_L:
                        case 3:
                            B[:, x0, y0, :] = (
                                1 / (12**2 * delta[k_L - 1] * delta[k_S - 1])
                            ) * (
                                -(
                                    -(A[:, x2, y2, :] - A[:, x_n2, y2, :])
                                    + 8 * (A[:, x1, y2, :] - A[:, x_n1, y2, :])
                                )
                                + (
                                    -(A[:, x2, y_n2, :] - A[:, x_n2, y_n2, :])
                                    + 8 * (A[:, x1, y_n2, :] - A[:, x_n1, y_n2, :])
                                )
                                + 8 * (
                                    -(A[:, x2, y1, :] - A[:, x_n2, y1, :])
                                    + 8 * (A[:, x1, y1, :] - A[:, x_n1, y1, :])
                                )
                                - 8 * (
                                    -(A[:, x2, y_n1, :] - A[:, x_n2, y_n1, :])
                                    + 8 * (A[:, x1, y_n1, :] - A[:, x_n1, y_n1, :])
                                )
                            )

                        case 4:
                            B[:, x0, :, y0] = (
                                1 / (12**2 * delta[k_L - 1] * delta[k_S - 1])
                            ) * (
                                -(
                                    -(A[:, x2, :, y2] - A[:, x_n2, :, y2])
                                    + 8 * (A[:, x1, :, y2] - A[:, x_n1, :, y2])
                                )
                                + (
                                    -(A[:, x2, :, y_n2] - A[:, x_n2, :, y_n2])
                                    + 8 * (A[:, x1, :, y_n2] - A[:, x_n1, :, y_n2])
                                )
                                + 8 * (
                                    -(A[:, x2, :, y1] - A[:, x_n2, :, y1])
                                    + 8 * (A[:, x1, :, y1] - A[:, x_n1, :, y1])
                                )
                                - 8 * (
                                    -(A[:, x2, :, y_n1] - A[:, x_n2, :, y_n1])
                                    + 8 * (A[:, x1, :, y_n1] - A[:, x_n1, :, y_n1])
                                )
                            )

                case 3:
                    match k_L:
                        case 4:
                            B[:, :, x0, y0] = (
                                1 / (12**2 * delta[k_L - 1] * delta[k_S - 1])
                            ) * (
                                -(
                                    -(A[:, :, x2, y2] - A[:, :, x_n2, y2])
                                    + 8 * (A[:, :, x1, y2] - A[:, :, x_n1, y2])
                                )
                                + (
                                    -(A[:, :, x2, y_n2] - A[:, :, x_n2, y_n2])
                                    + 8 * (A[:, :, x1, y_n2] - A[:, :, x_n1, y_n2])
                                )
                                + 8 * (
                                    -(A[:, :, x2, y1] - A[:, :, x_n2, y1])
                                    + 8 * (A[:, :, x1, y1] - A[:, :, x_n1, y1])
                                )
                                - 8 * (
                                    -(A[:, :, x2, y_n1] - A[:, :, x_n2, y_n1])
                                    + 8 * (A[:, :, x1, y_n1] - A[:, :, x_n1, y_n1])
                                )
                            )

    return B