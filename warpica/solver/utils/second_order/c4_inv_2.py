from array_api_compat import array_namespace

from warpica.solver.utils.second_order.c_det_2 import c_det_2


def c4_inv_2(cell_array):
    """Invert a 4 by 4 matrix of fields pointwise.

    Parameters
    ----------
    cell_array : array or nested sequence of arrays
        Matrix components indexed [i][j], with 4 rows and columns.

    Returns
    -------
    inverse : array
        Inverse with shape (4, 4, *grid_shape).

    Notes
    -----
    The matrix must be nonsingular at each grid cell.
    """
    if len(cell_array) != 4 or any(len(row) != 4 for row in cell_array):
        raise ValueError("cell_array is not 4x4")

    r = cell_array

    # Inverse by the adjugate: inverse[i][j] = (cofactor of r[j][i]) / det, with each
    # cofactor a signed 3x3 minor written out below (acts on whole grid arrays).
    det = c_det_2(r)

    xp = array_namespace(cell_array[0][0])

    inv_cell_array = xp.stack(
        tuple(
            xp.stack(tuple(row), axis=0)
            for row in [
                [
                    (1 / det)
                    * (
                        r[1][1] * r[2][2] * r[3][3]
                        - r[1][1] * r[2][3] * r[3][2]
                        - r[1][2] * r[2][1] * r[3][3]
                        + r[1][2] * r[2][3] * r[3][1]
                        + r[1][3] * r[2][1] * r[3][2]
                        - r[1][3] * r[2][2] * r[3][1]
                    ),
                    (1 / det)
                    * (
                        r[0][1] * r[2][3] * r[3][2]
                        - r[0][1] * r[2][2] * r[3][3]
                        + r[0][2] * r[2][1] * r[3][3]
                        - r[0][2] * r[2][3] * r[3][1]
                        - r[0][3] * r[2][1] * r[3][2]
                        + r[0][3] * r[2][2] * r[3][1]
                    ),
                    (1 / det)
                    * (
                        r[0][1] * r[1][2] * r[3][3]
                        - r[0][1] * r[1][3] * r[3][2]
                        - r[0][2] * r[1][1] * r[3][3]
                        + r[0][2] * r[1][3] * r[3][1]
                        + r[0][3] * r[1][1] * r[3][2]
                        - r[0][3] * r[1][2] * r[3][1]
                    ),
                    (1 / det)
                    * (
                        r[0][1] * r[1][3] * r[2][2]
                        - r[0][1] * r[1][2] * r[2][3]
                        + r[0][2] * r[1][1] * r[2][3]
                        - r[0][2] * r[1][3] * r[2][1]
                        - r[0][3] * r[1][1] * r[2][2]
                        + r[0][3] * r[1][2] * r[2][1]
                    ),
                ],
                [
                    (1 / det)
                    * (
                        r[1][0] * r[2][3] * r[3][2]
                        - r[1][0] * r[2][2] * r[3][3]
                        + r[1][2] * r[2][0] * r[3][3]
                        - r[1][2] * r[2][3] * r[3][0]
                        - r[1][3] * r[2][0] * r[3][2]
                        + r[1][3] * r[2][2] * r[3][0]
                    ),
                    (1 / det)
                    * (
                        r[0][0] * r[2][2] * r[3][3]
                        - r[0][0] * r[2][3] * r[3][2]
                        - r[0][2] * r[2][0] * r[3][3]
                        + r[0][2] * r[2][3] * r[3][0]
                        + r[0][3] * r[2][0] * r[3][2]
                        - r[0][3] * r[2][2] * r[3][0]
                    ),
                    (1 / det)
                    * (
                        r[0][0] * r[1][3] * r[3][2]
                        - r[0][0] * r[1][2] * r[3][3]
                        + r[0][2] * r[1][0] * r[3][3]
                        - r[0][2] * r[1][3] * r[3][0]
                        - r[0][3] * r[1][0] * r[3][2]
                        + r[0][3] * r[1][2] * r[3][0]
                    ),
                    (1 / det)
                    * (
                        r[0][0] * r[1][2] * r[2][3]
                        - r[0][0] * r[1][3] * r[2][2]
                        - r[0][2] * r[1][0] * r[2][3]
                        + r[0][2] * r[1][3] * r[2][0]
                        + r[0][3] * r[1][0] * r[2][2]
                        - r[0][3] * r[1][2] * r[2][0]
                    ),
                ],
                [
                    (1 / det)
                    * (
                        r[1][0] * r[2][1] * r[3][3]
                        - r[1][0] * r[2][3] * r[3][1]
                        - r[1][1] * r[2][0] * r[3][3]
                        + r[1][1] * r[2][3] * r[3][0]
                        + r[1][3] * r[2][0] * r[3][1]
                        - r[1][3] * r[2][1] * r[3][0]
                    ),
                    (1 / det)
                    * (
                        r[0][0] * r[2][3] * r[3][1]
                        - r[0][0] * r[2][1] * r[3][3]
                        + r[0][1] * r[2][0] * r[3][3]
                        - r[0][1] * r[2][3] * r[3][0]
                        - r[0][3] * r[2][0] * r[3][1]
                        + r[0][3] * r[2][1] * r[3][0]
                    ),
                    (1 / det)
                    * (
                        r[0][0] * r[1][1] * r[3][3]
                        - r[0][0] * r[1][3] * r[3][1]
                        - r[0][1] * r[1][0] * r[3][3]
                        + r[0][1] * r[1][3] * r[3][0]
                        + r[0][3] * r[1][0] * r[3][1]
                        - r[0][3] * r[1][1] * r[3][0]
                    ),
                    (1 / det)
                    * (
                        r[0][0] * r[1][3] * r[2][1]
                        - r[0][0] * r[1][1] * r[2][3]
                        + r[0][1] * r[1][0] * r[2][3]
                        - r[0][1] * r[1][3] * r[2][0]
                        - r[0][3] * r[1][0] * r[2][1]
                        + r[0][3] * r[1][1] * r[2][0]
                    ),
                ],
                [
                    (1 / det)
                    * (
                        r[1][0] * r[2][2] * r[3][1]
                        - r[1][0] * r[2][1] * r[3][2]
                        + r[1][1] * r[2][0] * r[3][2]
                        - r[1][1] * r[2][2] * r[3][0]
                        - r[1][2] * r[2][0] * r[3][1]
                        + r[1][2] * r[2][1] * r[3][0]
                    ),
                    (1 / det)
                    * (
                        r[0][0] * r[2][1] * r[3][2]
                        - r[0][0] * r[2][2] * r[3][1]
                        - r[0][1] * r[2][0] * r[3][2]
                        + r[0][1] * r[2][2] * r[3][0]
                        + r[0][2] * r[2][0] * r[3][1]
                        - r[0][2] * r[2][1] * r[3][0]
                    ),
                    (1 / det)
                    * (
                        r[0][0] * r[1][2] * r[3][1]
                        - r[0][0] * r[1][1] * r[3][2]
                        + r[0][1] * r[1][0] * r[3][2]
                        - r[0][1] * r[1][2] * r[3][0]
                        - r[0][2] * r[1][0] * r[3][1]
                        + r[0][2] * r[1][1] * r[3][0]
                    ),
                    (1 / det)
                    * (
                        r[0][0] * r[1][1] * r[2][2]
                        - r[0][0] * r[1][2] * r[2][1]
                        - r[0][1] * r[1][0] * r[2][2]
                        + r[0][1] * r[1][2] * r[2][0]
                        + r[0][2] * r[1][0] * r[2][1]
                        - r[0][2] * r[1][1] * r[2][0]
                    ),
                ],
            ]
        ),
        axis=0,
    )

    return inv_cell_array
